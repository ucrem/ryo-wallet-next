use std::fs;
use std::path::{Path, PathBuf};

use thiserror::Error;

use crate::rpc::{RpcCredentials, RpcError};

const MAX_LOGIN_BYTES: u64 = 512;

#[derive(Debug, Error)]
pub enum CredentialFileError {
    #[error("runtime directory must be absolute")]
    RelativeRuntimeDirectory,
    #[error("generated RPC credential file is not available yet")]
    NotReady,
    #[error("generated RPC credential file is missing, unsafe, or inaccessible")]
    UnsafeFile,
    #[error("generated RPC credential file exceeds its size limit")]
    TooLarge,
    #[error("generated RPC credential file is malformed")]
    InvalidContents,
}

/// Reads the login file generated by a managed `ryo-wallet-rpc` process. The
/// returned credentials remain Rust-only and redact their Debug representation.
pub fn read_generated_login(
    runtime_directory: &Path,
    rpc_port: u16,
) -> Result<RpcCredentials, CredentialFileError> {
    if !runtime_directory.is_absolute() {
        return Err(CredentialFileError::RelativeRuntimeDirectory);
    }
    let path = login_path(runtime_directory, rpc_port);
    let metadata = match fs::symlink_metadata(&path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Err(CredentialFileError::NotReady);
        }
        Err(_) => return Err(CredentialFileError::UnsafeFile),
    };
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Err(CredentialFileError::UnsafeFile);
    }
    if metadata.len() > MAX_LOGIN_BYTES {
        return Err(CredentialFileError::TooLarge);
    }
    check_owner_only(&metadata)?;
    let contents = fs::read(&path).map_err(|_| CredentialFileError::UnsafeFile)?;
    if contents.len() > MAX_LOGIN_BYTES as usize {
        return Err(CredentialFileError::TooLarge);
    }
    let value = std::str::from_utf8(&contents).map_err(|_| CredentialFileError::InvalidContents)?;
    let (username, password) = value
        .split_once(':')
        .ok_or(CredentialFileError::InvalidContents)?;
    RpcCredentials::new(username.to_owned(), password.to_owned()).map_err(map_credential_error)
}

pub fn login_path(runtime_directory: &Path, rpc_port: u16) -> PathBuf {
    runtime_directory.join(format!("ryo-wallet-rpc.{rpc_port}.login"))
}

fn map_credential_error(_error: RpcError) -> CredentialFileError {
    CredentialFileError::InvalidContents
}

#[cfg(unix)]
fn check_owner_only(metadata: &fs::Metadata) -> Result<(), CredentialFileError> {
    use std::os::unix::fs::MetadataExt;

    if metadata.mode() & 0o077 != 0 {
        return Err(CredentialFileError::UnsafeFile);
    }
    Ok(())
}

#[cfg(not(unix))]
fn check_owner_only(_metadata: &fs::Metadata) -> Result<(), CredentialFileError> {
    // Windows ACL verification is a dedicated platform adapter before release.
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;

    #[cfg(unix)]
    fn write_owner_only(path: &Path, contents: &[u8]) {
        use std::os::unix::fs::PermissionsExt;

        fs::write(path, contents).unwrap();
        fs::set_permissions(path, fs::Permissions::from_mode(0o600)).unwrap();
    }

    #[cfg(not(unix))]
    fn write_owner_only(path: &Path, contents: &[u8]) {
        fs::write(path, contents).unwrap();
    }

    #[test]
    fn reads_expected_generated_file_without_exposing_credentials() {
        let temp = tempfile::tempdir().unwrap();
        let path = login_path(temp.path(), 12345);
        write_owner_only(&path, b"ryo:generated-password");
        let credentials = read_generated_login(temp.path(), 12345).unwrap();
        assert_eq!(format!("{credentials:?}"), "RpcCredentials([REDACTED])");
    }

    #[test]
    fn rejects_unsafe_or_malformed_login_files() {
        let temp = tempfile::tempdir().unwrap();
        let path = login_path(temp.path(), 12345);
        assert!(matches!(
            read_generated_login(temp.path(), 12345),
            Err(CredentialFileError::NotReady)
        ));
        write_owner_only(&path, b"not-a-login");
        assert!(matches!(
            read_generated_login(temp.path(), 12345),
            Err(CredentialFileError::InvalidContents)
        ));
    }

    #[cfg(unix)]
    #[test]
    fn rejects_group_or_world_readable_login_file() {
        use std::os::unix::fs::PermissionsExt;

        let temp = tempfile::tempdir().unwrap();
        let path = login_path(temp.path(), 12345);
        fs::write(&path, b"ryo:generated-password").unwrap();
        fs::set_permissions(&path, fs::Permissions::from_mode(0o644)).unwrap();
        assert!(matches!(
            read_generated_login(temp.path(), 12345),
            Err(CredentialFileError::UnsafeFile)
        ));
    }
}
